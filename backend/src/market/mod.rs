//! 市场情绪指标（Market Sentiment Index, MSI）模块
//!
//! 本模块实现双周期市场情绪指数，用于衡量 A 股市场整体情绪：
//!
//! - **短期情绪 S-MSI**（n = 3~14 天）：基于每天每只股票的 *成交额* + *涨跌幅*，
//!   反映近期资金情绪（资金在追涨还是杀跌、涨跌广度如何）。
//! - **中期趋势 M-MSI**（N = 30~90 天）：基于每只股票的 *涨跌幅*（无成交额），
//!   反映中期趋势方向、动量持续性和结构健康度。
//!
//! 两个指数均映射到 `[0, 100]`，`50` 为中性线，组合成 3×3 九宫格信号矩阵。
//!
//! ## 等权设计
//!
//! 所有计算均采用**等权**（简单平均 / 计数），不按市值或成交额加权。
//! 这样能反映市场整体广度，避免少数大票扭曲指标——
//! 当指数涨但多数股票跌时，MSI 会如实反映偏空。

